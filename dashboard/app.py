            with r1:
                st.markdown(_metric_card_html("🟢 LOW STRESS", str(low_count), f"{low_count/total:.1%} of rows"), unsafe_allow_html=True)
            with r2:
                st.markdown(_metric_card_html("🔴 HIGH STRESS", str(high_count), f"{high_count/total:.1%} of rows"), unsafe_allow_html=True)
            with r3:
                st.markdown(_metric_card_html("TOTAL ROWS", str(total)), unsafe_allow_html=True)

