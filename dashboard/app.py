@st.cache_data(show_spinner=False)
def load_processed_data() -> dict:
    """Load CSVs/figures generated by the evaluation pipeline."""
    base = Path(__file__).resolve().parents[1]
    data_dir = base / "data" / "processed"
    features_dir = base / "data" / "features"
    reports_dir = base / "reports" / "figures"
    out = {}
    try:
        out["model_scores"] = pd.read_csv(data_dir / "model_comparison_scores.csv")
    except Exception:
        out["model_scores"] = None
    try:
        out["loso_results"] = pd.read_csv(data_dir / "loso_results.csv")
    except Exception:
        out["loso_results"] = None
    try:
        out["feature_imp"] = pd.read_csv(data_dir / "feature_importance.csv")
    except Exception:
        out["feature_imp"] = None
    raw_features = None
    for candidate in [
        data_dir / "processed_features.csv",
        features_dir / "stress_features.csv",
    ]:
        if candidate.is_file():
            try:
                raw_features = pd.read_csv(candidate)
                break
            except Exception:
                continue
    out["raw_features"] = raw_features
    out["fig_dir"] = reports_dir
    return out

def _training_data_hash() -> str:
    """Return a short hash of the training CSV so the model cache auto-invalidates
    when the underlying data changes."""
    processed_path = Path(__file__).resolve().parents[1] / "data" / "features" / "stress_features.csv"
    if processed_path.is_file():
        h = hashlib.md5(processed_path.read_bytes()).hexdigest()[:12]
        return h
    return "no_file"

@st.cache_resource(show_spinner=False)
def get_trained_model(_data_hash: str | None = None):
    """Train a RandomForest on the full processed dataset.

    The _data_hash parameter ensures Streamlit re-trains whenever the
    training CSV changes on disk (cache-busting).
    """
    processed_path = Path(__file__).resolve().parents[1] / "data" / "features" / "stress_features.csv"
    if processed_path.is_file():
        data = pd.read_csv(processed_path)
    else:
        data = load_processed_data()["raw_features"]
    if data is None:
        st.error("Processed feature table not found – cannot train model.")
        st.stop()
    X, y, _ = prepare_classification_data(data)
    pipeline = _build_model("rf")
    pipeline.fit(X, y)
    expected_cols = list(X.columns)
    # Store training label distribution for diagnostics
    train_info = {
        "n_rows": len(y),
        "n_low": int((y == 0).sum()),
        "n_high": int((y == 1).sum()),
        "classes": list(pipeline.classes_),
    }
    return pipeline, expected_cols, train_info

def validate_uploaded_csv(
    df: pd.DataFrame,
    expected_cols: list[str] | None = None,
) -> tuple[bool, str, pd.DataFrame | None]:
    """Validate that the uploaded CSV matches the model's expected feature schema.

    Parameters
    ----------
    df           : Raw uploaded DataFrame.
    expected_cols: The exact column list the trained model pipeline expects
                   (returned by get_trained_model).  Falls back to FEATURE_COLS
                   when not supplied.

    NaN values are ALLOWED — they will be imputed by the pipeline's SimpleImputer.
    """
    # Use the model's own column list when available so alignment is ensured.
    target_cols = expected_cols if expected_cols is not None else FEATURE_COLS

    df_clean = df.copy()

    # Legacy alias: the training CSV stores this as hr_rmssd_approx but the model
    # renames it to hr_diff_rms internally.  Mirror that rename here.
    if "hr_rmssd_approx" in df_clean.columns and "hr_diff_rms" not in df_clean.columns:
        df_clean = df_clean.rename(columns={"hr_rmssd_approx": "hr_diff_rms"})

    # Also handle the reverse alias so uploaded CSVs with either name work.
    if "hr_diff_rms" in df_clean.columns and "hr_rmssd_approx" not in df_clean.columns:
        df_clean["hr_rmssd_approx"] = df_clean["hr_diff_rms"]

    missing = [c for c in target_cols if c not in df_clean.columns]
    if missing:
        return False, (
            f"Missing {len(missing)} required feature column(s): {sorted(missing)}\n\n"
            f"Your CSV has {df.shape[1]} columns: {sorted(df.columns.tolist())}\n\n"
            f"Required features: {sorted(target_cols)}"
        ), None

    # Select and coerce only the columns the model expects, in the correct order.
    df_clean = df_clean[target_cols].copy()
    df_clean = df_clean.apply(pd.to_numeric, errors="coerce")

    nan_cols = df_clean.columns[df_clean.isnull().any()].tolist()
    nan_warn = ""
    if nan_cols:
        nan_warn = (
            f"\n*Note: {len(nan_cols)} column(s) contain missing values "
            f"({', '.join(nan_cols)}). "
            "They will be filled with median values from the training data.*"
        )
    return True, (
        f"CSV validation passed — {len(target_cols)} features matched.{nan_warn}"
    ), df_clean


def predict_stress(pipeline, X_new: pd.DataFrame) -> pd.Series:
    """Run the trained pipeline on new feature rows and return integer labels."""
    preds = pipeline.predict(X_new)
    return pd.Series(preds, name="predicted_stress")


def predict_stress_proba(pipeline, X_new: pd.DataFrame) -> pd.DataFrame | None:
    """Return per-class probabilities when the step supports predict_proba."""
    if not hasattr(pipeline, "predict_proba"):
        return None
    proba = pipeline.predict_proba(X_new)
    classes = pipeline.classes_          # actual order sklearn uses
    col_names = ["P(Low)" if int(c) == 0 else "P(High)" for c in classes]
    return pd.DataFrame(proba, columns=col_names)


def _label_from_pred(pred_value, pipeline=None) -> str:
    """Map a raw prediction value to a human-readable stress label.

    The training code in models.py uses:
      label 0 = stress_level < 5.0  (Low)
      label 1 = stress_level >= 5.0 (High)

    This mapping is hardcoded to be 100 % reliable regardless of
    pipeline.classes_ ordering or numpy int types.
    """
    return "High" if int(pred_value) == 1 else "Low"

