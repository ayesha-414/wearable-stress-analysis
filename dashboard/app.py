    if not dict_path.is_file():
        st.info(f"Data dictionary not found at `{dict_path}`.")
        return
    try:
        with open(dict_path, "rb") as file:
            header = file.read(512)
        if b"<svg" in header.lower() or b"<html" in header.lower():
            st.error("Data_Dictionary.csv contains SVG/HTML instead of CSV data.")
            return
        dict_df = None
        for enc in ("utf-8-sig", "cp1252", "latin-1"):
            try:
                dict_df = pd.read_csv(dict_path, encoding=enc)
                break
            except (UnicodeDecodeError, ValueError):
                continue
        if dict_df is None:
            st.error("Could not decode Data_Dictionary.csv.")
            return
        if dict_df.empty:
            st.info("The feature dictionary contains no rows.")
            return
        st.dataframe(dict_df.head(10), use_container_width=True)
    except (pd.errors.ParserError, OSError) as exc:
        st.error(f"Could not read the feature dictionary: {exc}")

